// Embeds the drizzle SQL migrations into packages/db-pg so a deployed Worker can migrate its own database
// (POST /internal/migrate). Run after `pnpm db:generate`; the Docker build runs it too.
// `--check` writes nothing and exits 1 when the embedded copy is stale (used by CI and the guard test).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../packages/db-pg/drizzle/", import.meta.url);
const journal = JSON.parse(readFileSync(new URL("meta/_journal.json", dir), "utf8"));
let previousWhen = -1;
let previousId = "00000000-0000-0000-0000-000000000000";
const snapshotIds = new Set();
for (const [index, entry] of journal.entries.entries()) {
  const prefix = String(index).padStart(4, "0");
  if (entry.idx !== index || !Number.isSafeInteger(entry.when) || entry.when <= previousWhen) throw new Error("Invalid migration journal order: regenerate pending migrations against the current base");
  const snapshot = JSON.parse(readFileSync(new URL(`meta/${prefix}_snapshot.json`, dir), "utf8"));
  if (!snapshot.id || snapshotIds.has(snapshot.id) || snapshot.prevId !== previousId) throw new Error(`Broken migration snapshot chain at ${entry.tag}: regenerate against the current base`);
  snapshotIds.add(snapshot.id);
  previousId = snapshot.id;
  previousWhen = entry.when;
}
const entries = journal.entries.map((e) => ({ tag: e.tag, when: e.when, sql: readFileSync(new URL(`${e.tag}.sql`, dir), "utf8") }));
const out = `// Generated by scripts/gen-migrations.mjs — do not edit.
export const MIGRATIONS: { tag: string; when: number; sql: string }[] = ${JSON.stringify(entries, null, 2)};
`;
const target = new URL("../packages/db-pg/src/migrations.generated.ts", import.meta.url);
if (process.argv.includes("--check")) {
  const tags = new Set(entries.map((e) => e.tag));
  const orphans = readdirSync(dir).filter((f) => f.endsWith(".sql") && !tags.has(f.slice(0, -4)));
  if (orphans.length) {
    console.error(`SQL files missing from drizzle/meta/_journal.json: ${orphans.join(", ")}`);
    process.exit(1);
  }
  if (readFileSync(target, "utf8") !== out) {
    console.error("packages/db-pg/src/migrations.generated.ts is out of date: run `node scripts/gen-migrations.mjs` and commit it");
    process.exit(1);
  }
  console.log(`embedded migrations are in sync (${entries.length})`);
} else {
  writeFileSync(target, out);
  console.log(`embedded ${entries.length} migrations`);
}
